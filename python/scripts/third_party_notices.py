"""Write THIRD_PARTY_NOTICES: the license notices for everything compiled
into the vpt._native extension, which every wheel must carry (MIT and the
other licenses involved require the notice with binary copies too).

    python scripts/third_party_notices.py          # (re)write the file
    python scripts/third_party_notices.py --check  # CI: fail if stale

Sources:
- Rust crates linked into the extension: `cargo tree` over normal
  dependencies, excluding proc-macro crates (those run at build time and
  aren't part of the binary). Each crate's license files are copied
  verbatim from the cargo registry (Cargo.lock pins the versions).
- Code adapted into src/ from other projects (NOTICES below): the
  CORE-MATH functions and fdlibm's atan2.

Run from python/ (the crate root).
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES"

CORE_MATH_LICENSE = (ROOT / "notices" / "core-math-LICENSE").read_text()

NOTICES = [
    (
        "CORE-MATH (correctly rounded sin, cos, tan, exp, log, log10, pow)",
        "https://core-math.gitlabpages.inria.fr/",
        "sin.c, cos.c, tan.c: Copyright (c) 2022-2025 Paul Zimmermann and Tom Hubrecht\n"
        "exp.c: Copyright (c) 2022-2025 Alexei Sibidanov.\n"
        "log.c: Copyright (c) 2022 INRIA and CERN.\n"
        "log10.c: Copyright (c) 2022-2025 INRIA and CERN.\n"
        "log/dint.h, log10/dint.h: Copyright (c) 2022 CERN.\n"
        "pow.c, pow.h: Copyright (c) 2022-2025 CERN and Inria\n"
        "pow/dint.h, pow/qint.h: Copyright (c) 2022, 2023 CERN and Inria\n\n" + CORE_MATH_LICENSE,
    ),
    (
        "fdlibm (atan2, transcribed in src/jmath.rs)",
        "https://www.netlib.org/fdlibm/",
        "Copyright (C) 1993 by Sun Microsystems, Inc. All rights reserved.\n\n"
        "Developed at SunSoft, a Sun Microsystems, Inc. business.\n"
        "Permission to use, copy, modify, and distribute this\n"
        "software is freely granted, provided that this notice\n"
        "is preserved.\n",
    ),
]


def linked_crates() -> list[dict]:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT
        )
    )
    by_id = {p["id"]: p for p in meta["packages"]}
    names = subprocess.check_output(
        ["cargo", "tree", "--locked", "-e", "normal,no-proc-macro", "--prefix", "none",
         "--format", "{p}"],
        cwd=ROOT, text=True,
    ).split("\n")
    wanted = {tuple(n.split()[:2]) for n in names if n.strip()}
    crates = [
        p for p in by_id.values()
        if (p["name"], "v" + p["version"]) in wanted and p["source"] is not None
    ]
    return sorted(crates, key=lambda p: p["name"])


def license_texts(pkg: dict) -> str:
    d = Path(pkg["manifest_path"]).parent
    files = sorted(
        f for f in d.iterdir()
        if f.is_file() and f.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE"))
    )
    if not files:
        sys.exit(f"{pkg['name']}: no license file found in {d}")
    return "\n".join(f"--- {f.name} ---\n{f.read_text().rstrip()}\n" for f in files)


def render() -> str:
    parts = [
        "Third-party notices for vpt's compiled extension (vpt/_native)\n"
        "================================================================\n\n"
        "vpt itself is MIT-licensed (LICENSE). Its native extension contains the\n"
        "code below; their notices are reproduced as their licenses require.\n"
        "Generated by scripts/third_party_notices.py -- do not edit by hand.\n"
    ]
    for title, url, text in NOTICES:
        parts.append(f"\n\n## {title}\n{url}\n\n{text.rstrip()}\n")
    for pkg in linked_crates():
        parts.append(
            f"\n\n## Rust crate {pkg['name']} {pkg['version']} ({pkg['license']})\n"
            f"{pkg.get('repository') or ''}\n\n{license_texts(pkg)}"
        )
    return "".join(parts)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("THIRD_PARTY_NOTICES is stale: run python scripts/third_party_notices.py")
        print("THIRD_PARTY_NOTICES is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
